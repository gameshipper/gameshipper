import * as path from 'node:path';
import { parseConfig } from '../../src/core/config/load.js';
import type { Config } from '../../src/core/config/schema.js';
import { runCapacitor } from '../../src/core/mobile/capacitor.js';
import { prepareMobileWorkspace } from '../../src/core/mobile/workspace.js';
import { testCtx } from './ctx.js';
import { makeTmpDir, writeFiles } from './tmp.js';

export function mobileConfig(extra: object = {}): Config {
  return parseConfig({ name: 'Moon Game', version: '1.2.3', mobile: { bundleId: 'com.jane.moongame' }, ...extra }).data!;
}

/** A real Capacitor platform folder, freshly generated by `cap add` (well under a second, offline). */
export async function generatedPlatform(target: 'ios' | 'android', config: Config = mobileConfig()) {
  const dir = makeTmpDir();
  const stageDir = path.join(dir, '.gameshipper', 'stage');
  writeFiles(stageDir, { 'index.html': '<!DOCTYPE html><html><head></head><body></body></html>' });
  const ctx = testCtx(dir);
  const workDir = prepareMobileWorkspace(ctx, config, stageDir);
  await runCapacitor(ctx, workDir, ['add', target]);
  return { dir, ctx, workDir, platformDir: path.join(workDir, target), config };
}
